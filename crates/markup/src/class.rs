impl std::fmt::Display for Class {
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        match self {
            Self::Hue(h) => write!(f, "h{h}"),
            Self::Ink(k) => write!(f, "k-{}", k.ink()),
            Self::Slot(s) => write!(f, "s{s}"),
            Self::Flashed(m) => f.write_str(m.name()),
            _ => f.write_str(self.name()),
        }
    }
}
