use units::*;

#[test]
fn fixed_rounds_like_javascript() {
    [
        (0.25, 1, "0.3"),
        (1.005, 2, "1.00"),
        (-0.04, 1, "-0.0"),
        (-0.25, 1, "-0.3"),
        (2.5, 0, "3"),
        (9.95, 1, "9.9"),
        (99.95, 1, "100.0"),
        (-0.0, 1, "0.0"),
        (0.05, 1, "0.1"),
        (123.456, 1, "123.5"),
    ]
    .into_iter()
    .for_each(|(x, d, s)| assert_eq!(Number::fixed(x, d), s, "{x}"));
}

#[test]
fn show_prints_like_javascript() {
    [
        (1e21, "1e+21"),
        (1.5e300, "1.5e+300"),
        (0.000001, "0.000001"),
        (1e-7, "1e-7"),
        (123.456, "123.456"),
        (-3.5, "-3.5"),
        (9007199254740994.0, "9007199254740994"),
        (5.0, "5"),
        (-0.0, "0"),
    ]
    .into_iter()
    .for_each(|(x, s)| assert_eq!(Number::show(x), s, "{x}"));
}
